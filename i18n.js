export const SUPPORTED_LANGUAGES = [
    { code: 'en', name: 'English', flag: '🇺🇸', dir: 'ltr' },
    { code: 'es', name: 'Español', flag: '🇪🇸', dir: 'ltr' },
    { code: 'fr', name: 'Français', flag: '🇫🇷', dir: 'ltr' },
    { code: 'pt', name: 'Português', flag: '🇧🇷', dir: 'ltr' },
    { code: 'id', name: 'Indonesia', flag: '🇮🇩', dir: 'ltr' },
    { code: 'ru', name: 'Русский', flag: '🇷🇺', dir: 'ltr' },
    { code: 'ar', name: 'العربية', flag: '🇸🇦', dir: 'rtl' }
];

export let activeLanguage = 'en';

export function t(key, lang = activeLanguage) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
}

export function setLanguage(langCode) {
    if (!TRANSLATIONS[langCode]) langCode = 'en';
    activeLanguage = langCode;

    try {
        localStorage.setItem('tradingpool_language', langCode);
    } catch (e) {}

    const langMeta = SUPPORTED_LANGUAGES.find(l => l.code === langCode) || SUPPORTED_LANGUAGES[0];

    if (typeof document !== 'undefined') {
        document.documentElement.lang = langCode;
        document.documentElement.dir = langMeta.dir;

        // Apply translations to all DOM elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const val = t(key, langCode);
            if (val) el.innerText = val;
        });

        // Apply translations to elements with data-i18n-title
        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            const val = t(key, langCode);
            if (val) el.title = val;
        });

        // Update header language select if present
        const langSelect = document.getElementById('lang-select');
        if (langSelect) langSelect.value = langCode;

        // Update header language button label
        const langLabel = document.getElementById('current-lang-label');
        if (langLabel) langLabel.innerText = `${langMeta.flag} ${langCode.toUpperCase()}`;

        // Update active class in dropdown
        document.querySelectorAll('.lang-opt-btn').forEach(btn => {
            if (btn.dataset.lang === langCode) btn.classList.add('active');
            else btn.classList.remove('active');
        });

        // Dispatch language change event for dynamic components
        if (typeof window !== 'undefined') {
            window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: langCode } }));
        }
    }

    return activeLanguage;
}

export function initLanguage() {
    let saved = 'en';
    try {
        saved = localStorage.getItem('tradingpool_language') || 'en';
    } catch (e) {}
    setLanguage(saved);
}
